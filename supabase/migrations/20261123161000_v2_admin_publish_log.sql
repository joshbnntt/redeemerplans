-- Applied to the production project on 2026-11-23 (Supabase migration "v2_admin_publish_log").
-- Who published which plan, when, and the resulting commit. Editors only.
create table public.plan_publishes (
  id bigint generated by default as identity primary key,
  plan_id text not null,
  title text not null,
  file_path text not null,
  commit_sha text not null,
  commit_url text,
  published_by uuid default auth.uid() references auth.users (id) on delete set null,
  published_at timestamptz not null default now()
);
create index plan_publishes_published_at_idx on public.plan_publishes (published_at desc);
create index plan_publishes_published_by_idx on public.plan_publishes (published_by);
alter table public.plan_publishes enable row level security;
create policy "Editors read the publish log" on public.plan_publishes for select to authenticated
  using ((select public.is_plan_editor()));
create policy "Editors add to the publish log" on public.plan_publishes for insert to authenticated
  with check ((select public.is_plan_editor()) and published_by = (select auth.uid()));
